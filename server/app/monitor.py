"""Context.dev Monitor webhook: "guideline updated" banner data (runbook section 3, step 5).

Context.dev facts used (from https://docs.context.dev/webhooks.md,
https://docs.context.dev/monitors/webhooks.md, https://docs.context.dev/api-reference/monitors/create.md
and https://docs.context.dev/api-reference/monitors/change.md, read 2026-11-19):

- Create a monitor: ``POST https://api.context.dev/v1/monitors`` with
  ``Authorization: Bearer <CONTEXT_DEV_API_KEY>`` (key needs ``monitors:write``). Body:
  ``{"name", "target": {"type": "page", "url"}, "schedule": {"type": "interval",
  "frequency", "unit": "minutes|hours|days"}, "webhook": {"url", "events": ["change.detected"],
  "retry": {}}}``. One ``page`` target is one URL, so each guideline URL gets its own monitor.
  201 response has ``id`` (e.g. ``mon_123``) and ``webhook.secret`` (generated by the API,
  read-only, may start with ``whsec_``). Rotate with ``POST /v1/monitors/{id}/webhook/rotate-secret``
  (old secret stops working immediately).
- Webhook headers: ``X-Context-Signature: t=<unix seconds>,v1=<hex>``, ``X-Context-Event``,
  ``X-Context-Id`` (stable across retries, for dedupe), ``X-Context-Delivery-Id``,
  ``X-Context-Attempt``.
- Signature: HMAC-SHA256, key = the secret string exactly as returned (``whsec_`` prefix
  included, not base64-decoded), message = ``f"{t}."`` + raw request body bytes, hex digest,
  constant-time compare. Verify before parsing JSON. The docs leave the timestamp tolerance
  to the receiver; their helper uses 300 s either way, and so does this module.
- Envelope: ``{"event": "change.detected" | "run.completed", "id", "created_at", "data":
  {"change": Change | null, "run": ...}}``.
- Change object: ``id`` (``chg_...``), ``monitor_id``, ``run_id``, ``target_type``, ``title``,
  ``summary``, ``detected_at`` (date-time), ``url`` (the monitored URL), plus optional
  ``diff``, ``importance``, ``evidence`` and others that are ignored here.
- Delivery: reply 2xx within 15 s. 408/429/5xx and network errors are retried; other 4xx are final.

Only changes whose URL host is in ``settings.guideline_domain_list`` (exact host or a
subdomain) are stored. The summary is truncated to 500 characters. Guideline pages are
public, so no patient data is involved; nothing from the body is logged.
"""

from __future__ import annotations

import hashlib
import hmac
import json
import time
from dataclasses import dataclass
from datetime import datetime, timezone
from typing import Any
from urllib.parse import urlparse, urlunparse

from app.retrieve import host_allowed

SIGNATURE_HEADER = "X-Context-Signature"
TOLERANCE_S = 300
SUMMARY_MAX_CHARS = 500
TITLE_MAX_CHARS = 300


class InvalidSignature(Exception):
    """Missing, malformed, stale or wrong ``X-Context-Signature``."""


@dataclass(frozen=True)
class GuidelineUpdate:
    id: str
    url: str
    title: str
    detected_at: datetime
    change_summary: str
    monitor_id: str | None


def sign(secret: str, body: bytes, timestamp: int) -> str:
    """Build an ``X-Context-Signature`` value (used by tests and local replays)."""
    digest = hmac.new(secret.encode(), f"{timestamp}.".encode() + body, hashlib.sha256).hexdigest()
    return f"t={timestamp},v1={digest}"


def split_secrets(value: str) -> list[str]:
    """``CONTEXT_DEV_WEBHOOK_SECRET`` may hold several comma-separated secrets: each page
    monitor gets its own secret, and the docs advise accepting old + new during rotation."""
    return [p.strip() for p in value.split(",") if p.strip()]


def verify_signature(secret: str, body: bytes, header: str | None, *, now: float | None = None) -> None:
    """Raise ``InvalidSignature`` unless ``header`` signs ``body`` with one of the
    comma-separated secrets in ``secret``, within tolerance."""
    secrets = split_secrets(secret)
    if not secrets:
        raise InvalidSignature("no secret configured")
    if not header:
        raise InvalidSignature("missing signature header")
    ts: str | None = None
    sigs: list[str] = []
    for part in header.split(","):
        key, _, value = part.strip().partition("=")
        if key == "t":
            ts = value
        elif key == "v1" and value:
            sigs.append(value)
    if ts is None or not ts.isdigit() or not sigs:
        raise InvalidSignature("malformed signature header")
    if abs((now if now is not None else time.time()) - int(ts)) > TOLERANCE_S:
        raise InvalidSignature("timestamp outside tolerance")
    message = f"{ts}.".encode() + body
    expected = [hmac.new(k.encode(), message, hashlib.sha256).hexdigest() for k in secrets]
    if not any(hmac.compare_digest(e, s) for e in expected for s in sigs):
        raise InvalidSignature("signature mismatch")


def normalize_url(url: str) -> str:
    """Compare URLs by scheme-less host + path: lowercase host, no fragment, no trailing slash."""
    try:
        p = urlparse(url.strip())
    except ValueError:
        return url.strip()
    host = (p.hostname or "").lower().rstrip(".")
    if host.startswith("www."):
        host = host[4:]
    path = p.path.rstrip("/")
    return urlunparse(("", host, path, "", p.query, ""))


def _parse_dt(value: Any) -> datetime:
    if isinstance(value, str) and value:
        try:
            dt = datetime.fromisoformat(value.replace("Z", "+00:00"))
            return (dt if dt.tzinfo else dt.replace(tzinfo=timezone.utc)).astimezone(timezone.utc)
        except ValueError:
            pass
    return datetime.now(timezone.utc)


def parse_changes(payload: dict[str, Any], domains: list[str]) -> list[GuidelineUpdate]:
    """Extract allowlisted guideline changes from a verified webhook payload."""
    data = payload.get("data") if isinstance(payload, dict) else None
    if not isinstance(data, dict):
        return []
    raw = data.get("change")
    changes = raw if isinstance(raw, list) else [raw]
    out: list[GuidelineUpdate] = []
    for ch in changes:
        if not isinstance(ch, dict):
            continue
        url = ch.get("url")
        if not isinstance(url, str) or not host_allowed(url, domains):
            continue
        change_id = ch.get("id") or payload.get("id")
        if not isinstance(change_id, str) or not change_id:
            continue
        summary = ch.get("summary") if isinstance(ch.get("summary"), str) else ""
        title = ch.get("title") if isinstance(ch.get("title"), str) else ""
        monitor_id = ch.get("monitor_id") if isinstance(ch.get("monitor_id"), str) else None
        out.append(GuidelineUpdate(
            id=change_id,
            url=url,
            title=title[:TITLE_MAX_CHARS],
            detected_at=_parse_dt(ch.get("detected_at")),
            change_summary=summary[:SUMMARY_MAX_CHARS],
            monitor_id=monitor_id,
        ))
    return out


def handle_webhook(store: Any, secret: str, body: bytes, signature: str | None, domains: list[str]) -> int:
    """Verify, parse and store. Returns how many new updates were stored.

    Raises ``InvalidSignature`` (caller answers 401) or ``ValueError`` for a non-JSON body.
    """
    verify_signature(secret, body, signature)
    payload = json.loads(body)
    return store.add_guideline_updates(parse_changes(payload, domains))
